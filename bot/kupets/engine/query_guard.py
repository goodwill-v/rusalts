"""Отсечение не-товарных запросов («привет!», «спасибо») до похода в поиск.

Раньше любое текстовое сообщение уходило в поиск по маркетплейсам, и бот
честно отвечал «Ничего не нашёл» на приветствие. Guard — чистая функция без
зависимостей (тестируется в CI без aiogram/structlog).
"""

from __future__ import annotations

import re

# Целиком болтовня/управление ботом (сравниваем по «в точности» в нижнем регистре)
_SMALLTALK_EXACT = {
    "привет", "прив", "приветик", "здравствуйте", "здравствуй", "добрый день",
    "добрый вечер", "доброе утро", "хай", "хэй", "hi", "hello", "hey", "yo",
    "спасибо", "спс", "благодарю", "пасиб", "thanks", "thx", "ок", "окей", "ok",
    "хорошо", "давай", "ну", "ага", "угу", "не", "да", "нет", "пока", "до свидания",
    "как дела", "что нового", "чем занят", "кто ты", "что умеешь", "help", "start",
}

# Приветствие в начале + не упомянут товар → болтовня
_GREETING_PREFIX = re.compile(
    r"^\s*(привет|прив|здравствуй\w*|добрый\s+(день|вечер)|доброе\s+утро|"
    r"хай|hi|hello|hey)\b[!,.?\s]*",
    re.IGNORECASE,
)

# Признаки товарного запроса (даже внутри приветствия)
_INTENT_WORDS = re.compile(
    r"(найди|найти|ищу|искать|нужен|нужна|нужно|купить|куплю|цена|цену|сколько стоит|"
    r"посоветуй|подбери|сравни|выбрать|выбери|заказать|маркетплейс|озон|ozon|"
    r"вайлдберриз|wildberries|яндекс маркет|со скидкой|дешевле|товар)",
    re.IGNORECASE,
)

# Только пунктуация/эмодзи/цифры-одиночки
_NOTHING_MEANINGFUL = re.compile(r"^[\W\d\s]+$")


def is_smalltalk(text: str) -> bool:
    """True — сообщение не товарный запрос, искать не надо."""
    t = (text or "").strip().lower()
    if not t:
        return True
    if t in _SMALLTALK_EXACT:
        return True
    if len(t) < 2 or _NOTHING_MEANINGFUL.match(t):
        return True
    if _INTENT_WORDS.search(t):
        return False
    # «Привет!» без товарной части — болтовня; «Привет, найди чайник» — запрос
    stripped = _GREETING_PREFIX.sub("", t)
    if stripped != t and (not stripped or len(stripped) < 3):
        return True
    return False
